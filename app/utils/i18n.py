_current_lang: str = "en"


def get_ui_language() -> str:
    """Return the current UI language code."""
    return _current_lang


def set_ui_language(lang_code: str):
    """Set the current UI language. Persists to config."""
    global _current_lang
    if lang_code in UI_LANGUAGES:
        _current_lang = lang_code
        app_config.set_value("ui_language", lang_code)


def _system_language() -> str:
    try:
        from PySide6.QtCore import QLocale
        code = QLocale.system().name().split("_")[0].lower()
    except Exception:
        import locale
        code = (locale.getlocale()[0] or "en").split("_")[0].lower()
    return code if code in UI_LANGUAGES else "en"


def init_i18n():
    """Idioma salvo, ou o do sistema na primeira execução. Chamar uma vez na inicialização."""
    global _current_lang
    saved = app_config.get("ui_language")
    _current_lang = saved if saved in UI_LANGUAGES else _system_language()


def tr(key: str, **kwargs) -> str:
    """
    Translate a UI string. Supports {placeholder} formatting.
    Falls back to English if the key is missing in the current language.
    """
    strings = _TRANSLATIONS.get(_current_lang, {})
    text = strings.get(key)
    if text is None:
        # Fallback to English
        text = _TRANSLATIONS.get("en", {}).get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text